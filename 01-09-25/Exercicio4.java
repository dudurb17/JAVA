public class Exercicio4 {
    public static void main(String[] args) {
        System.out.println("Tabuada do número 5:");
        System.out.println();
        
        for (int i = 1; i <= 10; i++) {
            int resultado = i * 5;
            System.out.println(i + " x 5 = " + resultado);
        }
    }
} 